import opencascade from "replicad-opencascadejs";
import { setOC } from "replicad";
import { runMug } from "../src/kernel/index.js";
import { buildMugSteps, disposeBuild } from "../src/kernel/mug.js";
import { meshShape } from "../src/kernel/mesh.js";
const rss = () => (process.memoryUsage().rss / 1048576).toFixed(0);
console.log("RSS before init", rss(), "MB");
const oc = await opencascade();
setOC(oc);
const mem = () => `wasm memory ${(oc.wasmMemory.buffer.byteLength / 1048576).toFixed(1)} MB, RSS ${rss()} MB`;
console.log("after init:", mem());
console.log("memory-ish exports:", Object.keys(oc).filter((k) => /sbrk|malloc|mallinfo|heap|memory|stack/i.test(k)).join(", "));
const wm = oc.wasmMemory;
console.log("WebAssembly.Memory type?", wm instanceof WebAssembly.Memory, "maximum?", (() => { try { return wm.type?.(); } catch (e) { return "n/a"; } })());
runMug({});
console.log("after 1 full run:", mem());
for (let i = 0; i < 20; i++) runMug({ height: 90 + i });
console.log("after 21 full runs:", mem());
// mesh-same-shape-twice: does BRepMesh reuse the cached triangulation?
const b = buildMugSteps({});
const last = b.steps.at(-1).shape;
let t = performance.now(); meshShape(last, { tolerance: 0.05, angularTolerance: 0.2 }); const first = performance.now() - t;
t = performance.now(); meshShape(last, { tolerance: 0.05, angularTolerance: 0.2 }); const second = performance.now() - t;
t = performance.now(); meshShape(last, { tolerance: 0.1, angularTolerance: 0.3 }); const coarser = performance.now() - t;
console.log(`mesh same shape: 1st ${first.toFixed(1)} ms, 2nd ${second.toFixed(1)} ms, then coarser tol ${coarser.toFixed(1)} ms`);
const t2 = performance.now(); oc.ReplicadMeshExtractor.mesh(last.wrapped, 0.05, 0.2); console.log("ReplicadMeshExtractor.mesh only (triangulate, no extraction):", (performance.now() - t2).toFixed(1), "ms");
disposeBuild(b);
const b2 = buildMugSteps({});
const fin = b2.steps.at(-1).shape;
const t3 = performance.now(); oc.ReplicadMeshExtractor.mesh(fin.wrapped, 0.05, 0.2); const triOnly = performance.now() - t3;
const t4 = performance.now(); meshShape(fin, { tolerance: 0.05, angularTolerance: 0.2 }); const extractAfter = performance.now() - t4;
console.log(`fresh shape: triangulate ${triOnly.toFixed(1)} ms, then extract (already triangulated) ${extractAfter.toFixed(1)} ms`);
const big = buildMugSteps({}).steps.at(-1).shape;
meshShape(big, { tolerance: 0.001, angularTolerance: 0.1 });
console.log("after one 0.001 mm mesh (300k tris):", mem());
